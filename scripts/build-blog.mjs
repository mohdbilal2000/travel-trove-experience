#!/usr/bin/env node
/**
 * Turns content/blog/*.md into data/generatedBlogPosts.ts (committed, so the build never depends
 * on this script having run). Runs automatically before `next build` (see package.json "prebuild").
 *
 *   node scripts/build-blog.mjs           # write data/generatedBlogPosts.ts
 *   node scripts/build-blog.mjs --check   # fail if the committed file is out of date
 *
 * File format: front matter between --- lines, then markdown. Scalars are `key: value`; lists are
 * `key: a | b | c` or `- item` lines. The body may end with a "## FAQ" section whose "### Question"
 * headings and following paragraph become the visible FAQ + FAQPage JSON-LD.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const DIR = "content/blog";
const OUT = "data/generatedBlogPosts.ts";
const AUTHOR = "Guide India Tours";
const ID_BASE = 1000;

export function parseFrontMatter(text, file = "") {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = {};
  let listKey = null;
  for (const line of m[1].split("\n")) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const item = line.match(/^\s*-\s+(.*)$/);
    if (item && listKey) {
      meta[listKey].push(item[1].trim());
      continue;
    }
    const kv = line.match(/^([A-Za-z][\w]*):\s*(.*)$/);
    if (!kv) throw new Error(`${file}: cannot parse front matter line "${line}"`);
    const [, k, v] = kv;
    if (v === "") {
      meta[k] = [];
      listKey = k;
    } else {
      meta[k] = v.trim().replace(/^["']|["']$/g, "");
      listKey = null;
    }
  }
  return { meta, body: m[2].trim() };
}

const list = (v) => (Array.isArray(v) ? v : String(v ?? "").split("|").map((s) => s.trim()).filter(Boolean));

export function splitFaq(body) {
  const idx = body.search(/^##\s+FAQ\s*$/m);
  if (idx < 0) return { content: body, faqs: [] };
  const content = body.slice(0, idx).trim();
  const faqBlock = body.slice(idx).replace(/^##\s+FAQ\s*$/m, "").trim();
  const faqs = [];
  for (const part of faqBlock.split(/^###\s+/m).map((s) => s.trim()).filter(Boolean)) {
    const nl = part.indexOf("\n");
    if (nl < 0) continue;
    faqs.push({ q: part.slice(0, nl).trim(), a: part.slice(nl + 1).trim().replace(/\n+/g, " ") });
  }
  return { content, faqs };
}

export function loadPosts(dir = DIR) {
  if (!existsSync(dir)) return [];
  const files = readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "README.md").sort();
  const posts = files.map((f, i) => {
    const { meta, body } = parseFrontMatter(readFileSync(join(dir, f), "utf8"), f);
    const { content, faqs } = splitFaq(body);
    const post = {
      id: ID_BASE + i,
      slug: meta.slug || f.replace(/\.md$/, ""),
      title: meta.title,
      excerpt: meta.excerpt,
      content,
      author: AUTHOR,
      publishedDate: meta.publishedDate,
      image: meta.image,
      category: meta.category || "Travel Tips",
      tags: list(meta.tags),
    };
    if (meta.updatedDate) post.updatedDate = meta.updatedDate;
    if (meta.relatedPlans) post.relatedPlans = list(meta.relatedPlans).map(Number);
    if (meta.relatedDestinations) post.relatedDestinations = list(meta.relatedDestinations);
    if (meta.faqQuestion) post.faqQuestion = meta.faqQuestion;
    if (meta.quickAnswer) post.quickAnswer = meta.quickAnswer;
    if (meta.takeaways) post.keyTakeaways = list(meta.takeaways);
    if (faqs.length) post.faqs = faqs;
    return post;
  });
  // Stable ids: oldest first.
  posts.sort((a, b) => a.publishedDate.localeCompare(b.publishedDate) || a.slug.localeCompare(b.slug));
  posts.forEach((p, i) => (p.id = ID_BASE + i));
  return posts;
}

export function render(posts) {
  return `// AUTO-GENERATED by scripts/build-blog.mjs from content/blog/*.md. Do not edit by hand.
import type { BlogPost } from "./blogPosts";

export const generatedBlogPosts: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`;
}

if (process.argv[1] && process.argv[1].endsWith("build-blog.mjs")) {
  const out = render(loadPosts());
  if (process.argv.includes("--check")) {
    const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (cur !== out) {
      console.error(`${OUT} is out of date. Run: node scripts/build-blog.mjs`);
      process.exit(1);
    }
    console.log(`${OUT} is up to date.`);
  } else {
    writeFileSync(OUT, out);
    console.log(`Wrote ${OUT} (${JSON.parse(JSON.stringify(loadPosts())).length} post(s)).`);
  }
}
